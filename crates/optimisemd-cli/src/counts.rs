//! The measured counts in docs/memory-process.md, generated and checked instead of typed.
//!
//! Ported from `scripts/memory-counts.sh`: the block is the one place the doc's figures live, and the check fails the
//! moment the tree and the block disagree, so the doc cannot claim a figure that was true last month. The bash script is
//! now the wrapper, and this module owns the rules.

use std::error::Error;
use std::fs;
use std::path::Path;
use std::process::Command;

use optimisemd_core::Store;

pub const DOC: &str = "docs/memory-process.md";
pub const START: &str = "<!-- measured:start";
pub const END: &str = "<!-- measured:end -->";
pub const MARKER: &str =
    "<!-- measured:start — do not hand-edit; run `bin/dsh-optimisemd counts --write` -->";

#[derive(Debug, Default, PartialEq)]
pub struct Counts {
    pub rows: usize,
    pub rules: usize,
    pub days: usize,
    pub parts: usize,
    pub runbooks: usize,
    pub steps: usize,
    pub memkb: usize,
    pub agents_lines: usize,
    pub agents_chars: usize,
}

/// The counts, taken the way their own checkers take them, so the block cannot disagree with the tree.
pub fn measure(root: &Path) -> Counts {
    let memory = root.join("MEMORY.md");
    let agents = root.join("AGENTS.md");
    let (agents_lines, agents_chars) = fs::read_to_string(&agents)
        .map(|s| {
            (
                s.as_bytes().iter().filter(|b| **b == b'\n').count(),
                s.chars().count(),
            )
        })
        .unwrap_or((0, 0));
    Counts {
        rows: count_lines(&memory, |l| l.starts_with("- **")),
        rules: count_lines(&root.join("docs/RULES.md"), |l| l.starts_with("| R-")),
        days: count_files(&root.join("memory"), |n| {
            n.starts_with("20") && n.ends_with(".md")
        }),
        parts: count_files(&root.join("docs/memory-details"), |n| n.ends_with(".md")),
        runbooks: count_files(&root.join("docs/runbooks"), |n| n.ends_with(".md")),
        steps: count_lines(&root.join("scripts/nightly-maintenance.sh"), |l| {
            l.starts_with("step \"") || l.starts_with("advisory_step \"")
        }),
        memkb: fs::metadata(&memory)
            .map(|m| m.len() as usize / 1024)
            .unwrap_or(0),
        agents_lines,
        agents_chars,
    }
}

fn count_lines(path: &Path, pred: impl Fn(&str) -> bool) -> usize {
    fs::read_to_string(path)
        .map(|s| s.lines().filter(|l| pred(l)).count())
        .unwrap_or(0)
}

fn count_files(dir: &Path, pred: impl Fn(&str) -> bool) -> usize {
    fs::read_dir(dir)
        .map(|it| {
            it.flatten()
                .filter(|e| e.file_type().map(|t| t.is_file()).unwrap_or(false))
                .filter(|e| pred(&e.file_name().to_string_lossy()))
                .count()
        })
        .unwrap_or(0)
}

/// The single block line, exactly in the doc's format.
pub fn block_line(c: &Counts, agent: &str, user: &str, date: &str) -> String {
    format!(
        "**Measured {date} — generated by `bin/dsh-optimisemd counts --write`; never hand-edited:** \
         {} fact rows · {} rules · {} daily logs · {} memory-detail parts · {} runbooks · {} nightly steps · \
         `MEMORY.md` {} KB · `AGENTS.md` {} lines / {} chars · plugin store {}/4,000 (agent) and {}/2,000 (preferences)",
        c.rows, c.rules, c.days, c.parts, c.runbooks, c.steps, c.memkb, c.agents_lines, c.agents_chars, agent, user
    )
}

/// The block's figures, from the tier-0 store the plugin owns; `?` when there is no store to read.
fn store_usage() -> (String, String) {
    let Some(path) = crate::store_path_read() else {
        return ("?".into(), "?".into());
    };
    let Ok(store) = Store::open(&path, Default::default()) else {
        return ("?".into(), "?".into());
    };
    let agent = store
        .usage("agent", "workspace")
        .map(|v| v.to_string())
        .unwrap_or_else(|_| "?".into());
    let user = store
        .usage("user", "user-global")
        .map(|v| v.to_string())
        .unwrap_or_else(|_| "?".into());
    (agent, user)
}

fn today() -> Result<String, Box<dyn Error>> {
    let out = Command::new("date").arg("+%F").output()?;
    if !out.status.success() {
        return Err("date +%F failed".into());
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

fn read_doc(root: &Path) -> Result<String, Box<dyn Error>> {
    Ok(fs::read_to_string(root.join(DOC))?)
}

/// The block line as the document holds it.
fn block_of(doc: &str) -> Option<String> {
    let re = regex::Regex::new(r"(?s)<!-- measured:start.*?-->\n(.*?)\n<!-- measured:end -->")
        .expect("constant regex");
    re.captures(doc)
        .and_then(|c| c.get(1))
        .map(|m| m.as_str().to_string())
}

fn strip_date(t: &str) -> String {
    let re = regex::Regex::new(r"Measured \d{4}-\d\d-\d\d").expect("constant regex");
    re.replace(t, "Measured").into_owned()
}

/// The summary the check prints when the block is current: the figures, without the date and the store caps.
fn summary(line: &str) -> &str {
    let rest = line.split(":** ").nth(1).unwrap_or(line);
    rest.split(" · plugin store").next().unwrap_or(rest)
}

pub fn check(root: &Path, want: &str) -> Result<i32, Box<dyn Error>> {
    let doc = read_doc(root)?;
    let Some(have) = block_of(&doc) else {
        println!(
            "{DOC}: no measured block — add <!-- measured:start --> … <!-- measured:end --> \
             (scripts/memory-counts.sh --write)"
        );
        return Ok(1);
    };
    if strip_date(&have) == strip_date(want) {
        println!(
            "measured counts: in step with the tree — {}",
            summary(&have)
        );
        return Ok(0);
    }
    println!("{DOC}: the measured block disagrees with the tree");
    println!("  in the doc: {have}");
    println!("  measured:   {want}");
    println!(
        "  fix: bin/dsh-optimisemd counts --write  \
         (then read the diff — a real change is worth knowing about)"
    );
    Ok(1)
}

pub fn write(root: &Path, want: &str) -> Result<i32, Box<dyn Error>> {
    let doc = read_doc(root)?;
    let (Some(start), Some(end)) = (doc.find(START), doc.find(END)) else {
        eprintln!(
            "no measured block in {DOC} — add <!-- measured:start --> … <!-- measured:end --> first"
        );
        return Ok(1);
    };
    if end < start {
        eprintln!(
            "no measured block in {DOC} — add <!-- measured:start --> … <!-- measured:end --> first"
        );
        return Ok(1);
    }
    let head = &doc[..start];
    let tail = match doc[end..].find('\n') {
        Some(k) => &doc[end + k + 1..],
        None => "",
    };
    let body = format!("{head}{MARKER}\n{want}\n{END}\n{tail}");
    fs::write(root.join(DOC), body)?;
    println!("wrote the measured block");
    Ok(0)
}

pub fn run(root: &Path, do_write: bool) -> Result<i32, Box<dyn Error>> {
    let counts = measure(root);
    let (agent, user) = store_usage();
    let want = block_line(&counts, &agent, &user, &today()?);
    if do_write {
        write(root, &want)
    } else {
        check(root, &want)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;
    use std::path::PathBuf;

    fn fixture() -> PathBuf {
        // Every test needs its own tree: they run in parallel in one process, and a shared path lets one test clobber
        // another's document (the first run of these tests did exactly that).
        static NEXT: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
        let n = NEXT.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
        let dir =
            std::env::temp_dir().join(format!("optimisemd-counts-{}-{n}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(dir.join("docs/memory-details")).unwrap();
        fs::create_dir_all(dir.join("docs/runbooks")).unwrap();
        fs::create_dir_all(dir.join("memory")).unwrap();
        fs::create_dir_all(dir.join("scripts")).unwrap();
        fs::write(
            dir.join("MEMORY.md"),
            "- **A.** (2026-01-01) — `docs/memory-details/01-a.md`\n\
             - **B.** (2026-01-02) — `docs/memory-details/01-a.md`\n\
             - **C.** (2026-01-03) — `docs/memory-details/01-a.md`\n",
        )
        .unwrap();
        fs::write(dir.join("AGENTS.md"), "one\ntwo\n").unwrap();
        fs::write(
            dir.join("docs/RULES.md"),
            "| R-1 | a |\n| R-2 | b |\nnot a rule\n",
        )
        .unwrap();
        fs::write(dir.join("docs/memory-details/01-a.md"), "# part\n").unwrap();
        fs::write(dir.join("docs/memory-details/02-b.md"), "# part\n").unwrap();
        fs::write(dir.join("docs/runbooks/r1.md"), "# runbook\n").unwrap();
        fs::write(dir.join("memory/2026-01-01.md"), "# day\n").unwrap();
        fs::write(dir.join("memory/2026-01-02.md"), "# day\n").unwrap();
        fs::write(
            dir.join("scripts/nightly-maintenance.sh"),
            "step \"a\" x\nadvisory_step \"b\" y\nnotstep \"c\"\n",
        )
        .unwrap();
        dir
    }

    fn doc_with(block: &str) -> String {
        format!("# doc\n\n{MARKER}\n{block}\n{END}\n\n## after\n")
    }

    fn want(dir: &std::path::Path) -> String {
        block_line(&measure(dir), "5", "10", "2026-11-16")
    }

    #[test]
    fn the_line_names_every_count_in_the_docs_order() {
        let c = measure(&fixture());
        assert_eq!(c.rows, 3);
        assert_eq!(c.rules, 2);
        assert_eq!(c.days, 2);
        assert_eq!(c.parts, 2);
        assert_eq!(c.runbooks, 1);
        assert_eq!(c.steps, 2);
        assert_eq!(c.memkb, 0);
        assert_eq!((c.agents_lines, c.agents_chars), (2, 8));
        assert_eq!(
            block_line(&c, "5", "10", "2026-11-16"),
            "**Measured 2026-11-16 — generated by `bin/dsh-optimisemd counts --write`; never hand-edited:** \
             3 fact rows · 2 rules · 2 daily logs · 2 memory-detail parts · 1 runbooks · 2 nightly steps · \
             `MEMORY.md` 0 KB · `AGENTS.md` 2 lines / 8 chars · plugin store 5/4,000 (agent) and 10/2,000 (preferences)"
        );
    }

    #[test]
    fn check_is_green_on_an_in_step_block_and_red_on_a_stale_one() {
        let dir = fixture();
        let good = want(&dir);
        fs::write(dir.join(DOC), doc_with(&good)).unwrap();
        assert_eq!(check(&dir, &good).unwrap(), 0);
        assert_eq!(
            check(&dir, &good.replace("3 fact rows", "4 fact rows")).unwrap(),
            1
        );
    }

    #[test]
    fn write_rewrites_a_stale_block_and_keeps_the_rest_of_the_file() {
        let dir = fixture();
        let good = want(&dir);
        fs::write(dir.join(DOC), doc_with("an old line")).unwrap();
        assert_eq!(write(&dir, &good).unwrap(), 0);
        assert_eq!(
            fs::read_to_string(dir.join(DOC)).unwrap(),
            format!("# doc\n\n{MARKER}\n{good}\n{END}\n\n## after\n")
        );
        assert_eq!(check(&dir, &good).unwrap(), 0);
    }

    #[test]
    fn write_stamps_the_date_even_when_only_the_date_changed() {
        let dir = fixture();
        let old = block_line(&measure(&dir), "5", "10", "2026-11-15");
        fs::write(dir.join(DOC), doc_with(&old)).unwrap();
        let new = want(&dir);
        assert_eq!(write(&dir, &new).unwrap(), 0);
        assert!(fs::read_to_string(dir.join(DOC))
            .unwrap()
            .contains("Measured 2026-11-16"));
    }

    #[test]
    fn a_document_without_the_markers_is_refused() {
        let dir = fixture();
        fs::write(dir.join(DOC), "# doc without a block\n").unwrap();
        assert_eq!(check(&dir, &want(&dir)).unwrap(), 1);
        assert_eq!(write(&dir, &want(&dir)).unwrap(), 1);
        assert_eq!(
            fs::read_to_string(dir.join(DOC)).unwrap(),
            "# doc without a block\n"
        );
    }
}
